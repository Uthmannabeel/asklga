export const DICT: Record<UiLang, Dict> = { en, pcm, ha, yo, ig };

export function dict(lang: UiLang): Dict {
  return DICT[lang] ?? en;
}

/** Server components: the interface language from the cookie set by /api/lang. */
export async function uiLang(): Promise<UiLang> {
  const jar = await cookies();
  const v = jar.get(LANG_COOKIE)?.value;
  return isUiLang(v) ? v : "en";
}

export function fill(template: string, n: number | string): string {
  return template.replace("%n", String(n));
}
